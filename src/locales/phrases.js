/**
 * Dynamic copy: row counters, ranges and "page x of y" phrases that embed
 * numbers. Capture groups map onto `$1…$n` in the replacement.
 */
export const PATTERNS = {
  en: [
    [/^نمایش (.+) تا (.+) از (.+) مورد$/, 'Showing $1–$2 of $3'],
    [/^صفحه (.+) از (.+)$/, 'Page $1 of $2'],
    [/^(.+) نتیجه$/, '$1 results'],
    [/^انتخاب ردیف (.+)$/, 'Select row $1'],
    [/^(.+) مورد$/, '$1 items'],
    [/^(.+) مورد باقی مانده$/, '$1 remaining'],
  ],
  ar: [
    [/^نمایش (.+) تا (.+) از (.+) مورد$/, 'عرض $1 إلى $2 من $3'],
    [/^صفحه (.+) از (.+)$/, 'الصفحة $1 من $2'],
    [/^(.+) نتیجه$/, '$1 نتيجة'],
    [/^انتخاب ردیف (.+)$/, 'تحديد الصف $1'],
    [/^(.+) مورد$/, '$1 عنصر'],
  ],
};

function build(index) {
  return PHRASES.reduce((book, row) => {
    const value = row[index];
    if (value) book[row[0]] = value;
    return book;
  }, {});
}

